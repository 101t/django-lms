#!/usr/bin/env bash
# Django LMS installer. Installs (or upgrades) the Docker stack on a Linux server.
#
#   curl -fsSL https://raw.githubusercontent.com/101t/django-lms/master/install.sh | sudo bash
#
# Optional environment variables:
#   DOMAIN=lms.example.edu   public domain; enables automatic HTTPS (otherwise plain HTTP on the server IP)
#   ADMIN_EMAIL=you@x.edu    email for the first admin account and Let's Encrypt
#   LMS_DIR=/opt/django-lms  where to install
#   LMS_VERSION=latest       image tag to run
#   SEED_DEMO=1              load demo courses and users
set -euo pipefail

REPO_RAW="https://raw.githubusercontent.com/101t/django-lms/${LMS_BRANCH:-master}"
LMS_DIR="${LMS_DIR:-/opt/django-lms}"
DOMAIN="${DOMAIN:-}"
ADMIN_EMAIL="${ADMIN_EMAIL:-admin@example.com}"

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }
rand() { # finite reads only: `tr </dev/urandom | head` dies of SIGPIPE under pipefail
	local s=""
	while [ "${#s}" -lt "$1" ]; do s+="$(head -c 512 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')"; done
	printf '%s' "${s:0:$1}"
}

[ "$(id -u)" -eq 0 ] || die "run as root, e.g.: curl -fsSL $REPO_RAW/install.sh | sudo bash"
command -v curl >/dev/null || die "curl is required"

if ! command -v docker >/dev/null; then
	say "Installing Docker (get.docker.com)"
	curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose ...)"

mkdir -p "$LMS_DIR"
cd "$LMS_DIR"
say "Downloading stack files into $LMS_DIR"
for file in docker-compose.yml Caddyfile; do
	curl -fsSL "$REPO_RAW/$file" -o "$file"
done

FIRST_INSTALL=0
if [ ! -f .env ]; then
	FIRST_INSTALL=1
	if [ -z "$DOMAIN" ] && [ -r /dev/tty ]; then
		read -rp "Domain name for this LMS (leave empty to use this server's IP over HTTP): " DOMAIN </dev/tty || true
	fi
	if [ -n "$DOMAIN" ]; then
		HOST="$DOMAIN" SITE_ADDRESS="$DOMAIN" SECURE=true URL="https://$DOMAIN"
	else
		HOST="$(hostname -I | awk '{print $1}')"
		[ -n "$HOST" ] || die "could not detect the server IP; re-run with DOMAIN=..."
		SITE_ADDRESS=":80" SECURE=false URL="http://$HOST"
	fi
	ADMIN_PASSWORD="$(rand 20)"
	say "Writing $LMS_DIR/.env"
	umask 077
	cat >.env <<ENV
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Edit, then run: docker compose up -d
LMS_VERSION=${LMS_VERSION:-latest}
SITE_ADDRESS=$SITE_ADDRESS
SITE_NAME=Django LMS
ALLOWED_HOSTS=$HOST
CSRF_TRUSTED_ORIGINS=$URL
SECURE_COOKIES=$SECURE
SECRET_KEY=$(rand 64)
POSTGRES_PASSWORD=$(rand 32)
TIME_ZONE=UTC

DJANGO_SUPERUSER_USERNAME=admin
DJANGO_SUPERUSER_EMAIL=$ADMIN_EMAIL
DJANGO_SUPERUSER_PASSWORD=$ADMIN_PASSWORD

# SMTP (leave EMAIL_HOST empty to log emails instead of sending them)
EMAIL_HOST=
EMAIL_PORT=587
EMAIL_HOST_USER=
EMAIL_HOST_PASSWORD=
DEFAULT_FROM_EMAIL=$ADMIN_EMAIL
ENV
else
	say "Keeping existing .env (upgrade)"
	URL="$(grep -E '^CSRF_TRUSTED_ORIGINS=' .env | cut -d= -f2-)"
fi

say "Pulling images"
docker compose pull --quiet
say "Starting services"
docker compose up -d --remove-orphans

say "Waiting for the app to become healthy"
for _ in $(seq 1 60); do
	[ "$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q web)" 2>/dev/null)" = healthy ] && break
	sleep 3
done
[ "$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q web)")" = healthy ] ||
	die "the web container is not healthy; check: cd $LMS_DIR && docker compose logs web"

if [ "${SEED_DEMO:-0}" = 1 ]; then
	say "Loading demo data"
	docker compose exec -T web python manage.py seed_demo
fi

printf '\n\033[1;32mDjango LMS is running at %s\033[0m\n' "$URL"
if [ "$FIRST_INSTALL" = 1 ]; then
	printf '  Admin user:     admin\n  Admin password: %s\n  (also stored in %s/.env — change it after signing in)\n' "$ADMIN_PASSWORD" "$LMS_DIR"
fi
printf '  Manage:  cd %s && docker compose logs -f | ps | down\n  Upgrade: re-run this installer\n' "$LMS_DIR"
